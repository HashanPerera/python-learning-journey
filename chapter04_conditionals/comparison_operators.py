"""
This file demonstrates: comparison_operators
- ==
- !=
- >
- <
- >=
- <=
"""

num1 = 10
num2 = 20

print("== :", num1 == num2)
print("!= :", num1 != num2)
print(">  :", num1 > num2)
print("<  :", num1 < num2)
print(">= :", num1 >= num2)
print("<= :", num1 <= num2)

print("\n=== String Comparison ===")

username = "admin"

print(username == "admin")
print(username != "guest")
