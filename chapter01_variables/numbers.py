"""
This file demonstrates:
- Integer and float data types
- Basic arithmetic operations
- Order of operations

Additionally, spaces have been set using '-'.
"""

# Integer
age = 25

# Float
height = 173.5

# Print values
print("Age:", age)
print("Height:", height)

# Printing '-' 30 times
print("-" * 30)

# Basic arithmetic
num1 = 10
num2 = 3

print("Addition:", num1 + num2)
print("Subtraction:", num1 - num2)
print("Multiplication:", num1 * num2)
print("Division:", num1 / num2)

# Printing '-' 30 times
print("-" * 30)

# Floor division and modulus
print("Floor Division:", num1 // num2)
print("Remainder (Modulus):", num1 % num2)

# Printing '-' 30 times
print("-" * 30)

# Exponentiation
print("Power:", num1 ** 2)

# Printing '-' 30 times
print("-" * 30)

# Order of operations (PEMDAS)
result = (5 + 3) * 2
print("Order of Operations:", result)

# Printing '-' 30 times
print("-" * 30)

# Updating variables
score = 50
print("Initial Score:", score)

score = score + 10
print("After Addition:", score)

score += 5
print("After += 5:", score)

score -= 3
print("After -= 3:", score)

# Printing '-' 30 times
print("-" * 30)
